#!/usr/bin/env python3
"""White-mask 24px tile glyphs → firmware RGB565A8 (recolor via LVGL)."""
from __future__ import annotations

import struct
import subprocess
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "tile_icons_src"
OUT_H = ROOT / "firmware" / "components" / "dashboard_shell" / "ui" / "tile_icons.h"
OUT_C = ROOT / "firmware" / "components" / "dashboard_shell" / "ui" / "tile_icons.cpp"
SIDE = 24

ICONS = [
    ("notebook", "notebook.svg"),
    ("todoist", "todoist.svg"),
]


def rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def decode_png(path: Path):
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    i = 8
    idat = b""
    w = h = bit = color = None
    while i < len(data):
        ln = struct.unpack(">I", data[i : i + 4])[0]
        i += 4
        typ = data[i : i + 4]
        i += 4
        chunk = data[i : i + ln]
        i += ln + 4
        if typ == b"IHDR":
            w, h, bit, color = struct.unpack(">IIBB", chunk[:10])
        elif typ == b"IDAT":
            idat += chunk
        elif typ == b"IEND":
            break
    raw = zlib.decompress(idat)
    assert color == 6 and bit == 8
    bpp, stride = 4, w * 4
    rows: list[bytearray] = []
    for y in range(h):
        filt = raw[y * (stride + 1)]
        row = bytearray(raw[y * (stride + 1) + 1 : (y + 1) * (stride + 1)])
        if filt == 1:
            for x in range(bpp, len(row)):
                row[x] = (row[x] + row[x - bpp]) & 255
        elif filt == 2:
            prev = rows[y - 1] if y else bytearray(stride)
            for x in range(len(row)):
                row[x] = (row[x] + prev[x]) & 255
        elif filt == 3:
            prev = rows[y - 1] if y else bytearray(stride)
            for x in range(len(row)):
                left = row[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + ((left + prev[x]) // 2)) & 255
        elif filt == 4:

            def paeth(a, b, c):
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                if pa <= pb and pa <= pc:
                    return a
                return b if pb <= pc else c

            prev = rows[y - 1] if y else bytearray(stride)
            for x in range(len(row)):
                a = row[x - bpp] if x >= bpp else 0
                b = prev[x]
                c = prev[x - bpp] if x >= bpp else 0
                row[x] = (row[x] + paeth(a, b, c)) & 255
        rows.append(row)
    return w, h, rows


def pack_white_mask(png: Path) -> bytes:
    w, h, rows = decode_png(png)
    assert w == h == SIDE
    color = bytearray()
    alpha = bytearray()
    for row in rows:
        for x in range(w):
            r, g, b, a = row[x * 4 : x * 4 + 4]
            luma = (r + g + b) // 3
            if a == 0:
                ink = 0
            elif luma >= 128:
                ink = a
            else:
                ink = int(a * (255 - luma) / 255)
            c = rgb565(255, 255, 255)
            color += bytes((c & 0xFF, (c >> 8) & 0xFF))
            alpha.append(ink)
    return bytes(color + alpha)


def main() -> None:
    parts = []
    for cname, svg_name in ICONS:
        svg = SRC / svg_name
        png = SRC / f"{cname}.png"
        subprocess.check_call(
            ["rsvg-convert", "-w", str(SIDE), "-h", str(SIDE), "--background-color", "none", str(svg), "-o", str(png)]
        )
        parts.append((cname, pack_white_mask(png)))

    lines = [
        "// Generated by tools/gen_tile_icons.py — do not edit.",
        '#include "ui/tile_icons.h"',
        "",
        f"static constexpr int kSide = {SIDE};",
        f"static constexpr size_t kBytes = {SIDE * SIDE * 3};",
        "",
    ]
    for cname, packed in parts:
        lines.append(f"static const uint8_t {cname}_data[kBytes] = {{")
        row: list[str] = []
        for b in packed:
            row.append(f"0x{b:02X}")
            if len(row) == 16:
                lines.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ", ".join(row) + ",")
        lines.append("};")
        lines.append("")

    lines += [
        "namespace {",
        "lv_image_dsc_t make(const uint8_t *data) {",
        "    lv_image_dsc_t image = {};",
        "    image.header.magic = LV_IMAGE_HEADER_MAGIC;",
        "    image.header.cf = LV_COLOR_FORMAT_RGB565A8;",
        "    image.header.w = kSide;",
        "    image.header.h = kSide;",
        "    image.header.stride = kSide * 2;",
        "    image.data_size = kBytes;",
        "    image.data = data;",
        "    return image;",
        "}",
        "}  // namespace",
        "",
    ]
    for cname, _ in parts:
        lines.append(f"const lv_image_dsc_t &tile_icons::{cname}() {{")
        lines.append(f"    static const lv_image_dsc_t image = make({cname}_data);")
        lines.append("    return image;")
        lines.append("}")
        lines.append("")

    OUT_C.write_text("\n".join(lines))
    OUT_H.write_text(
        "// Generated by tools/gen_tile_icons.py — do not edit.\n"
        "#pragma once\n"
        "#include <lvgl.h>\n"
        "\n"
        "namespace tile_icons {\n"
        "const lv_image_dsc_t &notebook();\n"
        "const lv_image_dsc_t &todoist();\n"
        "}  // namespace tile_icons\n"
    )
    print("wrote", OUT_C.relative_to(ROOT))


if __name__ == "__main__":
    main()
